class MemberMapTests(unittest.TestCase):
    def test_upper_and_mixed_case_lowered(self):
        self.assertEqual(member_map(['PLEDIT.TXT']), {'pledit.txt': 'PLEDIT.TXT'})
        self.assertEqual(member_map(['VisColor.InI']), {'viscolor.ini': 'VisColor.InI'})

    def test_subfolder_key_is_basename(self):
        self.assertEqual(member_map(['skins/bmp/TITLEBAR.BMP']), {'titlebar.bmp': 'skins/bmp/TITLEBAR.BMP'})

    def test_folder_entries_skipped(self):
        self.assertEqual(member_map(['dir/', 'dir\\', 'file.txt']), {'file.txt': 'file.txt'})

    def test_first_duplicate_wins(self):
        names = ['a/pledit.txt', 'b/PLEDIT.TXT']
        self.assertEqual(member_map(names), {'pledit.txt': 'a/pledit.txt'})



class AllowedMembersTests(unittest.TestCase):
    def test_oversized_member_skipped_later_still_allowed(self):
        mb = 1024 * 1024
        infos = [
            ('big.bmp', MAX_MEMBER_BYTES + 1),
            ('ok.bmp', mb),
            ('ok2.bmp', mb),
        ]
        self.assertEqual(allowed_members(infos), {'ok.bmp', 'ok2.bmp'})

    def test_total_cut_at_30_mb(self):
        mb = 1024 * 1024
        infos = [(f'f{i}.bmp', mb) for i in range(32)]
        kept = allowed_members(infos)
        self.assertEqual(kept, {f'f{i}.bmp' for i in range(30)})

    def test_exact_caps_allowed(self):
        infos = [('edge.bmp', MAX_MEMBER_BYTES)]
        self.assertEqual(allowed_members(infos), {'edge.bmp'})


class ParsePleditTests(unittest.TestCase):
    def test_normal_file(self):
        text = (
            '[text]\n'
            'normal=#00ffaa\n'
            'current=#FFFFFF\n'
            'normalbg=#000000\n'
            'selectedbg=#0000C6\n'
            'Font=Comic Sans\n'
        )
        self.assertEqual(parse_pledit(text), {
            'normal': '#00ffaa',
            'current': '#ffffff',
            'normalbg': '#000000',
            'selectedbg': '#0000c6',
            'font': 'Comic Sans',
        })

    def test_colors_without_hash(self):
        text = 'normal=00ffaa\ncurrent=ffffff\n'
        got = parse_pledit(text)
        self.assertEqual(got['normal'], '#00ffaa')
        self.assertEqual(got['current'], '#ffffff')

    def test_lowercase_output(self):
        got = parse_pledit('normal=#ABCDEF\n')
        self.assertEqual(got['normal'], '#abcdef')

    def test_bad_color_keeps_default(self):
        for value in ('#12g456', '#12345', 'zzz', '#1234567', ''):
            got = parse_pledit('normal=%s\n' % value)
            self.assertEqual(got['normal'], DEFAULT_PLEDIT['normal'], value)

    def test_trailing_comment_cut(self):
        got = parse_pledit('normal=#123456 ; my color\ncurrent=#abcdef// note\n')
        self.assertEqual(got['normal'], '#123456')
        self.assertEqual(got['current'], '#abcdef')

    def test_font_kept(self):
        got = parse_pledit('Font=Trebuchet MS\n')
        self.assertEqual(got['font'], 'Trebuchet MS')

    def test_unknown_keys_ignored(self):
        got = parse_pledit('weird=stuff\nnumber1=2\n')
        self.assertEqual(got, DEFAULT_PLEDIT)

    def test_empty_text_gives_defaults(self):
        self.assertEqual(parse_pledit(''), DEFAULT_PLEDIT)

    def test_comment_and_section_lines_skipped(self):
        text = '; comment\n// slash comment\n[text]\nnormal=#112233\n'
        got = parse_pledit(text)
        self.assertEqual(got['normal'], '#112233')


class ParseViscolorTests(unittest.TestCase):
    def test_24_lines_with_comments(self):
        lines = ['; viscolor', '// generated by skin builder']
        for i in range(24):
            lines.append('%d,%d,%d' % (i, i * 2, i * 3))
        got = parse_viscolor('\n'.join(lines))
        self.assertEqual(len(got), 24)
        self.assertEqual(got[0], (0, 0, 0))
        self.assertEqual(got[23], (23, 46, 69))
        for color, default in zip(got, DEFAULT_VISCOLORS):
            self.assertEqual(len(color), 3)

    def test_short_file_filled_from_defaults(self):
        text = '1,2,3\n4,5,6\n'
        got = parse_viscolor(text)
        self.assertEqual(len(got), 24)
        self.assertEqual(got[0], (1, 2, 3))
        self.assertEqual(got[1], (4, 5, 6))
        for i in range(2, 24):
            self.assertEqual(got[i], DEFAULT_VISCOLORS[i])

    def test_numbers_over_255_clamped(self):
        text = '300, 5, 999\n'   # only digits count, so a minus sign would make the line junk
        got = parse_viscolor(text)
        self.assertEqual(got[0], (255, 5, 255))

    def test_junk_lines_skipped(self):
        text = '\n'.join(['garbage line', 'no numbers here', '9,8,7', '', '; comment'])
        got = parse_viscolor(text)
        self.assertEqual(got[0], (9, 8, 7))
        self.assertEqual(len(got), 24)

    def test_returns_tuples(self):
        got = parse_viscolor('10,20,30\n')
        self.assertIsInstance(got[0], tuple)


class ParseRegionTests(unittest.TestCase):
    def test_one_section_two_polygons(self):
        text = (
            '[Normal]\n'
            'NumPoints=4,3\n'
            'PointList=0,0, 10,0, 10,10 0,10, 0,0, 1,1, 2,2\n'
        )
        got = parse_region(text)
        self.assertEqual(list(got), ['normal'])
        self.assertEqual(got['normal'], [
            [(0, 0), (10, 0), (10, 10), (0, 10)],
            [(0, 0), (1, 1), (2, 2)],
        ])

    def test_count_mismatch_dropped(self):
        text = (
            '[Normal]\n'
            'NumPoints=4\n'
            'PointList=0,0, 1,1, 2,2\n'
        )
        self.assertEqual(parse_region(text), {})

    def test_count_below_three_dropped(self):
        text = (
            '[Normal]\n'
            'NumPoints=2\n'
            'PointList=0,0, 1,1\n'
        )
        self.assertEqual(parse_region(text), {})

    def test_unknown_sections_ignored(self):
        text = (
            '[Other]\n'
            'NumPoints=3\n'
            'PointList=0,0, 1,1, 2,2\n'
            '[Normal]\n'
            'NumPoints=3\n'
            'PointList=0,0, 1,1, 2,2\n'
        )
        got = parse_region(text)
        self.assertEqual(list(got), ['normal'])
        self.assertEqual(got['normal'], [[(0, 0), (1, 1), (2, 2)]])

    def test_spaces_and_commas_mixed_in_pointlist(self):
        text = (
            '[Equalizer]\n'
            'NumPoints=3\n'
            'PointList=0, 0 ,  10,20\t,30, 40\n'
        )
        got = parse_region(text)
        self.assertEqual(got['equalizer'], [[(0, 0), (10, 20), (30, 40)]])

    def test_later_keys_overwrite_earlier(self):
        text = (
            '[Normal]\n'
            'NumPoints=9\n'
            'NumPoints=3\n'
            'PointList=0,0, 1,1, 2,2\n'
        )
        got = parse_region(text)
        self.assertEqual(got['normal'], [[(0, 0), (1, 1), (2, 2)]])


